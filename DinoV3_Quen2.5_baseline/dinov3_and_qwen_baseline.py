results = []
for idx, row in tqdm(df.iterrows(), total=len(df)):
    img_path = os.path.join(images_folder, row["image_id"] + ".jpg")
    question = row["question"]
    gt_answer = str(row["answer"]).strip().lower()
    try:
        pred_answer = run_vqa(img_path, question)
    except Exception as e:
        pred_answer = f"Error: {e}"

    results.append({
        "image_id": row["image_id"],
        "question": question,
        "gt_answer": gt_answer,
        "pred_answer": pred_answer
    })

results_df = pd.DataFrame(results)
results_df.to_csv("dinov2_qwen_baseline_predictions.csv", index=False)
