def exact_match(pred, gt):
    return int(pred.strip().lower() == gt.strip().lower())

results_df["exact_match"] = [
    exact_match(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])
]
accuracy = results_df["exact_match"].mean()
print(f"Exact Match Accuracy: {accuracy:.4f}")

from difflib import SequenceMatcher
def similarity(a, b):
    return SequenceMatcher(None, a.lower(), b.lower()).ratio()

results_df["similarity"] = [
    similarity(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])
]
mean_sim = results_df["similarity"].mean()
print(f"Semantic Similarity: {mean_sim:.4f}")

import nltk
from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction
nltk.download('punkt')

def compute_bleu(pred, gt):
    smoothie = SmoothingFunction().method4
    return sentence_bleu([gt.lower().split()], pred.lower().split(), smoothing_function=smoothie)

results_df["bleu"] = [compute_bleu(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])]
mean_bleu = results_df["bleu"].mean()
print(f"BLEU Score: {mean_bleu:.4f}")

