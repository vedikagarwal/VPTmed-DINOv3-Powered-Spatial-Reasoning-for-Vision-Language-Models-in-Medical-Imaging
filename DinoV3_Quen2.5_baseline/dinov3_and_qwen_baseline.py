def run_vqa(image_path, question, max_new_tokens=80):
    emb = extract_features(image_path)
    emb_str = " ".join([f"{x:.4f}" for x in emb[:32]])

    messages = [
        {"role": "system",
         "content": "You are a helpful medical assistant answering questions about medical images."},
        {"role": "user",
         "content": f"The image embedding is: {emb_str}\n\nQuestion: {question}\nPlease provide a short, medically relevant answer."}
    ]

    prompt = tokenizer.apply_chat_template(messages, add_generation_prompt=True, tokenize=False)
    inputs = tokenizer(prompt, return_tensors="pt").to("cuda")

    with torch.no_grad():
        output = text_model.generate(**inputs, max_new_tokens=max_new_tokens)

    answer = tokenizer.decode(output[0], skip_special_tokens=True)

    for key in ["assistant", "Assistant", "Answer:", "answer:"]:
        if key in answer:
            answer = answer.split(key)[-1].strip()

    return answer

img_path = os.path.join(images_folder, df.loc[0, "image_id"] + ".jpg")
