from tqdm import tqdm

results = []

for idx, row in tqdm(df.iterrows(), total=len(df)):
    image_id = row["image_id"]
    question = row["question"]
    gt_answer = str(row["answer"]).strip().lower()

    img_path = os.path.join(images_folder, image_id + ".jpg")

    try:
        pred_answer = run_vqa(model, processor, img_path, question)
    except Exception as e:
        pred_answer = f"Error: {e}"

    results.append({
        "image_id": image_id,
        "question": question,
        "gt_answer": gt_answer,
        "pred_answer": pred_answer
    })

results_df = pd.DataFrame(results)
results_df.to_csv("qwen2_5_vl_baseline_predictions.csv", index=False)
print("Saved results to qwen2_5_vl_baseline_predictions.csv")

def exact_match(pred, gt):
    return int(pred.strip().lower() == gt.strip().lower())

results_df["exact_match"] = [
    exact_match(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])
]

accuracy = results_df["exact_match"].mean()
print(f"Baseline Exact Match Accuracy: {accuracy:.4f}")

from difflib import SequenceMatcher

def similarity(a, b):
    return SequenceMatcher(None, a.lower(), b.lower()).ratio()

results_df["similarity"] = [
    similarity(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])
]

mean_sim = results_df["similarity"].mean()
print(f"Baseline Semantic Similarity Score: {mean_sim:.4f}")

