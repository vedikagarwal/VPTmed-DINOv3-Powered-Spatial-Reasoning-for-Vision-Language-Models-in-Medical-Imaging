def run_vqa(model, processor, image_path, question, max_new_tokens=50):

    image = Image.open(image_path).convert("RGB")


    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text", "text": question}
            ],
        }
    ]


    prompt = processor.apply_chat_template(messages, add_generation_prompt=True)


    inputs = processor(
        text=prompt,
        images=[image],
        return_tensors="pt"
    )
    inputs = {k: v.to("cuda") for k, v in inputs.items()}


    output = model.generate(**inputs, max_new_tokens=max_new_tokens)


    raw_answer = processor.batch_decode(output, skip_special_tokens=True)[0]


    if "assistant" in raw_answer.lower():
        answer = raw_answer.lower().split("assistant")[-1].strip()
    else:
        answer = raw_answer.strip()

    return answer

