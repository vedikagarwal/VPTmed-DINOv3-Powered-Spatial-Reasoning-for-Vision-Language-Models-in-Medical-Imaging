import nltk
from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction

# Download the tokenizer if not already
nltk.download('punkt')

def compute_bleu(pred, gt):
    smoothie = SmoothingFunction().method4
    reference = [gt.lower().split()]
    candidate = pred.lower().split()
    return sentence_bleu(reference, candidate, smoothing_function=smoothie)

results_df["bleu"] = [
    compute_bleu(p, g) for p, g in zip(results_df["pred_answer"], results_df["gt_answer"])
]

mean_bleu = results_df["bleu"].mean()
